#: Files in ``data/`` that rs-metadata maintains itself.
PROJECT_OWNED_DATA = ("placeholders.json",)


@cache
def format_hints() -> dict[str, Any]:
    """How other packaging ecosystems spell things rs-metadata maps.

    Returns
    -------
    dict
        ``rLicenseAliases`` mapping CRAN license strings to SPDX identifiers,
        and ``pyprojectUrlRoles`` mapping CodeMeta concepts to the PEP 621
        ``[project.urls]`` labels that denote them.

    Examples
    --------
    >>> format_hints()["rLicenseAliases"]["aliases"]["gpl-3"]
    'GPL-3.0-only'
    >>> "repository" in format_hints()["pyprojectUrlRoles"]["labels"]["source"]
    True
    """
    return load(DATA_PACKAGE, "format-hints.json")


@cache
def concept_order() -> tuple[str, ...]:
    """The order concepts are reported in.

    Returns
    -------
    tuple of str
        Mandatory fields first, in the order the profile declares them, then
        recommended ones. Concepts absent from both sort after these,
        alphabetically, so adding a property never makes the report unstable.

    Notes
    -----
    Derived from the profile rather than kept in a file of its own: the profile
    already lists its fields in a deliberate order, identity before provenance
    before technical detail, and repeating that order elsewhere is one more
    thing to keep in step.

    Examples
    --------
    >>> concept_order()[:3]
    ('name', 'description', 'version')
    """
    policy = profile_field_policy()
    return (*policy["mandatory"], *policy["recommended"])


@cache
def placeholders() -> dict[str, Any]:
    """Template values that get left behind, and how to recognize them.

    Returns
    -------
    dict
        ``orcid``, ``doiPrefix``, ``hosts``, and ``patterns`` carrying regex
        sources compiled by :mod:`rs_metadata.profile.placeholders`.

    Examples
    --------
    >>> placeholders()["orcid"]
    '0000-0000-0000-0000'
    >>> "example.com" in placeholders()["hosts"]
    True
    """
    return load(DATA_PACKAGE, "placeholders.json")


@cache
def spdx_index() -> dict[str, str]:
    """Case-insensitive lookup from an SPDX identifier to its canonical case.

    SPDX identifiers are case-sensitive by specification, but people write
    ``apache-2.0`` constantly. Recognising the value and reporting the
    canonical spelling is more useful than rejecting it outright.
    """
    return {
        identifier.casefold(): identifier for identifier in spdx_licenses()["licenses"]
    }


@cache
def profile_field_policy() -> dict[str, list[str]]:
    """The mandatory and recommended field lists, read from the profile schema.

    The schema is the single source of truth. Duplicating these lists in
    Python would let documentation, validator and schema drift apart.

    Returns
    -------
    dict
        ``mandatory``, ``recommended`` and ``featureListAliases`` lists.

    Examples
    --------
    >>> policy = profile_field_policy()
    >>> len(policy["mandatory"])
    10
    >>> "license" in policy["mandatory"]
    True
    >>> "keywords" in policy["recommended"]
    True

    The mandatory list matches the schema's own ``required`` keyword, which a
    contract test enforces:

    >>> set(policy["mandatory"]) <= set(profile_schema()["required"])
    True
    """
    block = profile_schema()["x-lumc-profile"]
    return {
        "mandatory": list(block["mandatory"]),
        "recommended": list(block["recommended"]),
        "featureListAliases": list(block["featureListAliases"]),
    }
