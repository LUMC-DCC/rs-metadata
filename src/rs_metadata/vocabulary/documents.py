"""Schemas, vocabularies and rule data read at runtime.

Two kinds of file live in ``data/``. Vendored ones have an upstream, a
checksum and a refresh script. Project-owned ones are maintained by
hand and the refresh script never touches them; a contract test keeps
the two sets disjoint.
"""

from __future__ import annotations

from functools import cache
from typing import Any, cast

from .loader import DATA_PACKAGE, SCHEMA_PACKAGE, load
from .properties import codemeta_terms


@cache
def codemeta_versions() -> dict[str, Any]:
    """Which ``@context`` values are recognized, and what 2.0 terms became.

    Returns
    -------
    dict
        ``current``, ``currentMajor``, and a ``contexts`` map from context URL
        to version.

    Examples
    --------
    Every 3.x context denotes the current vocabulary — 3.0 and 3.1 resolve to
    byte-identical documents, so a 3.0 record is not out of date:

    >>> versions = codemeta_versions()
    >>> versions["contexts"]["https://w3id.org/codemeta/3.0"]
    '3.0'
    >>> versions["currentMajor"]
    '3'

    Earlier CodeMeta is not listed, and is reported as an unrecognized
    context:

    >>> any(v.startswith("2") for v in versions["contexts"].values())
    False
    """
    return codemeta_terms()


@cache
def cff_schema() -> dict[str, Any]:
    """The official Citation File Format 1.2.0 JSON Schema."""
    return load(DATA_PACKAGE, "cff-1.2.0.schema.json")


@cache
def codemeta_crosswalks() -> dict[str, Any]:
    """CodeMeta's own crosswalk tables, keyed by the mapping id that uses them.

    Each entry is ``{"source", "format", "properties"}``, where ``properties``
    maps a CodeMeta property to the source fields CodeMeta says correspond to
    it. Vendored so a mapping's claim about its own provenance can be checked
    rather than believed.
    """
    document = load(DATA_PACKAGE, "codemeta-crosswalks.json")
    return cast(dict[str, Any], document["crosswalks"])


@cache
def profile_schema() -> dict[str, Any]:
    """The LUMC CodeMeta profile schema."""
    return load(SCHEMA_PACKAGE, "codemeta-lumc.schema.json")


@cache
def report_schema() -> dict[str, Any]:
    """The JSON schema describing rs-metadata's own report format."""
    return load(SCHEMA_PACKAGE, "rs-metadata-report.schema.json")


@cache
def spdx_licenses() -> dict[str, Any]:
    """SPDX identifiers mapped to name, deprecation status and OSI approval."""
    return load(DATA_PACKAGE, "spdx-licenses.json")


@cache
def vocabularies() -> dict[str, Any]:
    """Controlled vocabularies with no stable machine-readable upstream form."""
    return load(DATA_PACKAGE, "vocabularies.json")


@cache
def provenance() -> dict[str, Any]:
    """Where each vendored file came from, and when."""
    return load(DATA_PACKAGE, "provenance.json")


